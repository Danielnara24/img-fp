/// The fastest of several runs: the slow ones are the machine's, not the
/// code's.
fn ms(f: impl Fn()) -> f64 {
    let mut best = f64::MAX;
    for _ in 0..9 {
        let t = std::time::Instant::now();
        f();
        best = best.min(t.elapsed().as_secs_f64() * 1000.0);
    }
    best
}

