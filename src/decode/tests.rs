// Everything `decode` says about each file of a list, hashed a line a file,
// so that two builds can be compared file by file, the way a change to this
// module is checked:
// `IMGFP_FILES=list IMGFP_OUT=out cargo test --release --lib -- --ignored decode::tests::fingerprints`

fn hash(f: impl FnOnce(&mut std::collections::hash_map::DefaultHasher)) -> u64 {
    let mut h = std::collections::hash_map::DefaultHasher::new();
    f(&mut h);
    h.finish()
}

fn guarded<T>(f: impl FnOnce() -> T) -> Result<T, String> {
    std::panic::catch_unwind(std::panic::AssertUnwindSafe(f)).map_err(|_| "panic".to_string())
}

fn line(path: &Path) -> String {
    let mut out = vec![path.display().to_string()];
    let probe = guarded(|| probe(path)).ok().flatten();
    let len = std::fs::metadata(path).map_or(0, |m| m.len());
    out.push(match &probe {
        Some(p) => format!("probe {}x{} cost {:?}", p.w, p.h, crate::progress::file_cost(Some(p), len, 512, 512)),
        None => "probe none".into(),
    });
    for work in [512, 160] {
        out.push(match decode_guarded(|| decode_with(path, work, probe.as_ref())) {
            Ok(d) => {
                let t = d.traits;
                format!(
                    "decode{work} {}x{} {:016x} size {:?} damaged {:?} detail {:?} colour {:08x} grid {:016x} lossless {} exif {} frames {}",
                    d.work.w,
                    d.work.h,
                    hash(|h| d.work.px.iter().for_each(|v| v.to_bits().hash(h))),
                    d.size,
                    d.damaged,
                    t.detail.map(f32::to_bits),
                    t.colour.to_bits(),
                    hash(|h| t.grid.iter().for_each(|v| v.to_bits().hash(h))),
                    t.lossless,
                    t.exif,
                    t.frames
                )
            }
            Err(e) => format!("decode{work} error {e:#}"),
        });
    }
    out.push(match guarded(|| colour_of(path)) {
        Ok(c) => format!("colour {:?}", c.map(f32::to_bits)),
        Err(e) => format!("colour {e}"),
    });
    out.push(match guarded(|| chroma_of(path)) {
        Ok(c) => format!("chroma {:?}", c.map(|c| hash(|h| c.iter().flatten().for_each(|v| v.to_bits().hash(h))))),
        Err(e) => format!("chroma {e}"),
    });
    let shown = |r: anyhow::Result<(u32, u32, Vec<u8>)>| match r {
        Ok((w, h, px)) => format!("{w}x{h} {:016x}", hash(|hs| px.hash(hs))),
        Err(e) => format!("error {e:#}"),
    };
    out.push(format!("preview {}", shown(guarded(|| preview(path, 256)).unwrap_or_else(|e| Err(anyhow::anyhow!(e))))));
    for (w, h, cover) in [(300, 200, false), (300, 200, true), (64, 64, true), (1000, 1000, false)] {
        let r = guarded(|| preview_fit(path, w, h, cover)).unwrap_or_else(|e| Err(anyhow::anyhow!(e)));
        out.push(format!("fit{w}x{h}{} {}", if cover { "c" } else { "" }, shown(r)));
    }
    out.join("\t")
}

