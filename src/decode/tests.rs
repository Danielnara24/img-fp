/// What the analysis makes of a picture a reader hands to `read`: its
/// working plane, its shown size, and its traits.
fn analyse(work: usize, read: impl FnOnce(&mut dyn Sink) -> Result<()>) -> Result<(Gray, (u32, u32), Traits)> {
    let mut sink = Reduce::new(work);
    read(&mut sink)?;
    sink.finish()
}

/// The working plane of a picture held whole in memory, `layout` a pixel.
fn reduced(w: usize, h: usize, data: &[u8], layout: Layout, work: usize) -> Gray {
    analyse(work, |sink| {
        let n = sink.begin(&Rows { w, h, layout, orientation: picture::Orientation::NoTransforms, grey_of_colour: false });
        for y in 0..n {
            sink.row(&data[y * w * layout.ch()..(y + 1) * w * layout.ch()]);
        }
        Ok(())
    })
    .unwrap()
    .0
}

/// `working_size` is the working plane the reduction makes, whatever the
/// picture's shape: the progress bar costs a file by it.
#[test]
fn the_working_size_is_the_planes() {
    for (w, h) in [(37, 23), (2000, 1500), (1500, 2000), (4000, 300), (300, 4000), (1025, 1), (1, 1025), (513, 384), (512, 384), (9, 7), (6000, 4000)] {
        for work in [0, 64, 128, 512] {
            let data = vec![128u8; w * h];
            let g = reduced(w, h, &data, Layout::Grey, work);
            assert_eq!((g.w, g.h), working_size(w, h, work), "{w}x{h}@{work}");
        }
    }
}

/// What a file says of itself, as `decode` reads it.
fn facts_of(bytes: &[u8]) -> Facts {
    let kind = sniff::identify(bytes, Path::new("x")).expect("a picture");
    (open(kind, bytes).unwrap().facts)()
}


/// A header claiming more pixels than the machine has memory for is an
/// error for that file, not an allocation that aborts the process: an
/// 18 KB BMP claiming 96 x 788 million pixels asked for 227 GB, and the
/// whole scan ended with it.
#[test]
fn a_header_claiming_too_many_pixels_is_refused_not_allocated() {
    let mut bmp = Vec::new();
    let (w, h): (i32, i32) = (96, -788_529_016);
    let data = vec![0x80u8; 96 * 3 * 64];
    bmp.extend_from_slice(b"BM");
    bmp.extend_from_slice(&((54 + data.len()) as u32).to_le_bytes());
    bmp.extend_from_slice(&[0, 0, 0, 0]);
    bmp.extend_from_slice(&54u32.to_le_bytes());
    bmp.extend_from_slice(&40u32.to_le_bytes());
    bmp.extend_from_slice(&w.to_le_bytes());
    bmp.extend_from_slice(&h.to_le_bytes());
    bmp.extend_from_slice(&1u16.to_le_bytes());
    bmp.extend_from_slice(&24u16.to_le_bytes());
    bmp.extend_from_slice(&[0u8; 24]);
    bmp.extend_from_slice(&data);
    let dir = std::env::temp_dir().join(format!("img-fp-huge-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let p = dir.join("huge.bmp");
    std::fs::write(&p, &bmp).unwrap();
    let err = decode(&p, 512).err().expect("refused").to_string();
    assert!(err.contains("needs"), "{err}");
    assert!(preview(&p, 256).is_err());
    std::fs::remove_dir_all(&dir).ok();
}

